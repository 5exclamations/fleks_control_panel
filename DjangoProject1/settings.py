def env_bool(name, default):
    value = os.getenv(name, '').strip().lower()
    if not value:
        return default
    return value in ('1', 'true', 'yes', 'on')


def env_list(name, default):
    value = os.getenv(name, '').strip()
    if not value:
        return default
    return [item.strip() for item in value.split(',') if item.strip()]


